    private FSRainbow() {
    }

    public static int count() {
        return NAMES.length;
    }

    public static String name(int style) {
        int index = (style % NAMES.length + NAMES.length) % NAMES.length;
        return NAMES[index];
    }

    /** Arcoiris clasico por tono. */
    public static int hue(float h) {
        return 0xFFFFFF & Color.HSBtoRGB(h - (float) Math.floor(h), 0.9F, 1.0F);
    }

    /**
     * Color de un estilo en una posicion del texto (0..1) y un instante (0..1).
     */
    public static int color(int style, float pos, float time) {
        if (style <= 0) {
            return hue(pos + time);
        }

        int[] palette = PALETTES[(style - 1) % PALETTES.length];
        float x = pos + time;
        x -= (float) Math.floor(x);
        float scaled = x * palette.length;
        int i = (int) Math.floor(scaled) % palette.length;
        int j = (i + 1) % palette.length;
        float f = scaled - (float) Math.floor(scaled);
        return FSColors.lerp(palette[i], palette[j], f);
    }
